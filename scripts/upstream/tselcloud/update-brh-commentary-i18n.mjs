const expectedKeys = Object.keys(TRANSLATIONS.fr).sort();

for (const [language, commentary] of Object.entries(TRANSLATIONS)) {
  const keys = Object.keys(commentary).sort();
  if (keys.join("|") !== expectedKeys.join("|")) {
    throw new Error(
      `Langue « ${language} » : jeu de clés différent du français.\n` +
        `  manquantes : ${expectedKeys.filter((key) => !keys.includes(key)).join(", ") || "—"}\n` +
        `  en trop    : ${keys.filter((key) => !expectedKeys.includes(key)).join(", ") || "—"}`,
    );
  }

  const file = path.join(ROOT, "src/i18n", language, "common.json");
  const json = JSON.parse(readFileSync(file, "utf8"));
  json.bible ??= {};
  json.bible.commentary = commentary;
  writeFileSync(file, `${JSON.stringify(json, null, 2)}\n`, "utf8");
  console.log(`[i18n] ${language} — bible.commentary (${keys.length} clés)`);
}

console.log(`[i18n] ${Object.keys(TRANSLATIONS).length} langues mises à jour.`);
